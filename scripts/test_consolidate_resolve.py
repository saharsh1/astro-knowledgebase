#!/usr/bin/env python
"""Offline tests of /consolidate (candidates, gather, topic names) and /resolve (conflict copies).

    python scripts/test_consolidate_resolve.py
"""
from __future__ import annotations

import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
SCRIPTS = ["check_vault.py", "kb_common.py", "consolidate.py", "resolve_conflicts.py"]
FAILS: list[str] = []


def expect(name: str, ok: bool, detail: str = "") -> None:
    print(("PASS " if ok else "FAIL ") + name)
    if not ok:
        FAILS.append(name)
        print("     " + detail.strip().replace("\n", "\n     "))


def write(path: Path, fm: str, body: str = "") -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(f"---\n{fm.strip()}\n---\n{body}\n", encoding="utf-8")


def lesson(root: Path, arm: str, author: str, title: str, key: str, extra: str = "", body: str = "") -> str:
    stem = f"2026-11-1{len(title) % 9} - {author} - {title}"
    tags = "[Gaia, NSS]" if arm == "binary-stars" else "[Gaia]"      # NSS is a binary-stars tag
    write(root / "live" / arm / "lessons" / f"{stem}.md",
          f"title: {title}\ntype: lesson\nkind: tip\nauthor: {author}\ncreated: 2026-11-13\n"
          f"last_checked: 2026-11-13\nstatus: current\napplies_to: ['{key}']\ntags: {tags}\n{extra}", body)
    return stem


def run(root: Path, script: str, *args: str) -> tuple[int, str]:
    r = subprocess.run([sys.executable, str(root / "scripts" / script), *args],
                       capture_output=True, text=True, cwd=root)
    return r.returncode, r.stdout + r.stderr


def as_user(root: Path, user: str) -> None:
    subprocess.run(["git", "-C", str(root), "config", "github.user", user], check=True)


def main() -> int:
    with tempfile.TemporaryDirectory() as t:
        root = Path(t) / "vault"
        (root / "scripts").mkdir(parents=True)
        for s in SCRIPTS:
            shutil.copy(REPO / "scripts" / s, root / "scripts" / s)
        shutil.copytree(REPO / "templates", root / "templates")
        conv = yaml.safe_load((REPO / "conventions.yaml").read_text())
        conv["owner"] = "owner1"
        (root / "conventions.yaml").write_text(yaml.safe_dump(conv, sort_keys=False))
        subprocess.run(["git", "init", "-q", str(root)], check=True)
        as_user(root, "alice")
        for arm in conv["arms"]:
            (root / "live" / arm / "notes").mkdir(parents=True)

        key = "dr3:nss_two_body_orbit.period"
        old = lesson(root, "binary-stars", "alice", "Period unit", key)
        new = lesson(root, "binary-stars", "bob", "Period unit is days", key, f"supersedes: ['[[{old}]]']")
        mw = lesson(root, "milky-way", "carol", "Period in kinematic samples", key)
        other = lesson(root, "binary-stars", "bob", "Eccentricity", "dr3:nss_two_body_orbit.eccentricity")
        write(root / "live/binary-stars/topics/Topic - NSS period - alice - 2026-11-13.md",
              f"title: Topic - NSS period - alice - 2026-11-13\ntype: topic\nauthor: alice\ncreated: 2026-11-13\n"
              f"consolidates: ['[[{new}]]']\ntags: [NSS]",
              "> [!note] Generated by a model on 2026-11-13.")

        code, out = run(root, "check_vault.py")
        expect("the sample vault passes the checker", code == 0, out)

        # --- /consolidate ---------------------------------------------------------------------
        code, out = run(root, "consolidate.py", "candidates")
        line = next((l for l in out.splitlines() if key in l), "")
        expect("candidates: the shared column is listed, 1 new of 2 current",
               line.split()[:2] == ["1", "2"] and "Topic - NSS period" in line, out)
        expect("candidates: the superseded lesson is not counted as current", old not in out, out)
        expect("candidates: common tags (Gaia) are not used as topics", "tag Gaia" not in out, out)
        expect("candidates: a column with one note is not listed", "eccentricity" not in out, out)

        code, out = run(root, "consolidate.py", "gather", "--applies-to", "nss_two_body_orbit.period")
        expect("gather: all three lessons, across arms", all(s in out for s in (old, new, mw)) and other not in out, out)
        expect("gather: the superseded one is marked", f"superseded by {new}" in out, out)
        expect("gather: the one in a topic is marked", "in topic Topic - NSS period" in out, out)
        expect("gather: names the topic note a new version must supersede",
               "Existing topic notes on this: Topic - NSS period - alice - 2026-11-13" in out
               and "supersedes" in out, out)
        code, out = run(root, "consolidate.py", "gather", "--applies-to", "period", "--arm", "milky-way")
        expect("gather --arm: one arm only", mw in out and new not in out, out)

        bad = root / "live/binary-stars/topics/Topic - NSS period - 2026-11-14.md"
        write(bad, "title: x\ntype: topic\nauthor: alice\ncreated: 2026-11-14\nconsolidates: []\ntags: []")
        code, out = run(root, "check_vault.py")
        expect("a topic file name without its author is refused", code == 1 and "pattern for a topic" in out, out)
        bad.unlink()

        # --- /resolve ---------------------------------------------------------------------------
        orig = root / "live/binary-stars/lessons" / f"{old}.md"
        copy = orig.with_name(f"{old} (SFConflict bob@example.org 2026-11-13-10-00-00).md")
        copy.write_text(orig.read_text().replace("tags: [Gaia, NSS]", "tags: [Gaia, NSS, Orbits]"))
        code, out = run(root, "check_vault.py")
        expect("the checker reports the conflict copy", code == 1 and "conflict copy" in out, out)

        as_user(root, "bob")
        code, out = run(root, "resolve_conflicts.py")
        expect("list: bob sees it is alice's to settle", "for alice to settle" in out, out)
        code, out = run(root, "resolve_conflicts.py", "--keep", "copy", str(copy.relative_to(root)))
        expect("keep: bob may not settle alice's conflict", code != 0 and "Only alice" in out and copy.exists(), out)

        as_user(root, "alice")
        code, out = run(root, "resolve_conflicts.py", "--show", str(copy.relative_to(root)))
        expect("show: who saved the copy, and the difference",
               "saved by bob@example.org" in out and "+tags: [Gaia, NSS, Orbits]" in out, out)
        code, out = run(root, "resolve_conflicts.py", "--keep", "copy", str(copy.relative_to(root)))
        trashed = list((root / ".resolve-trash").rglob(f"{old}.md"))
        expect("keep copy: the copy's text replaces the original; the old original is kept in the trash",
               code == 0 and not copy.exists() and "Orbits" in orig.read_text() and len(trashed) == 1, out)

        twin = orig.with_name(f"{old} (SFConflict carol 2026-11-13-11-00-00).md")
        twin.write_bytes(orig.read_bytes())
        as_user(root, "carol")
        code, out = run(root, "resolve_conflicts.py", "--keep", "original", str(twin.relative_to(root)))
        expect("an identical copy: anyone may drop it", code == 0 and not twin.exists(), out)

        k = root / "keeper/generated/Home (SFConflict dave 2026-11-13-12-00-00).md"
        k.parent.mkdir(parents=True)
        k.write_text("a")
        (root / "keeper/generated/Home.md").write_text("b")
        as_user(root, "alice")
        code, out = run(root, "resolve_conflicts.py", "--keep", "copy", str(k.relative_to(root)))
        expect("keeper/: only the owner settles", code != 0 and "Only owner1" in out, out)

        code, out = run(root, "check_vault.py")
        live_errors = [l for l in out.splitlines() if l.startswith("error: live/")]
        expect("live/ is clean again; the keeper/ conflict waits for the owner",
               not live_errors and "keeper/generated/Home (SFConflict" in out, out)

    print(f"\n{len(FAILS)} failed" if FAILS else "\nall passed")
    return 1 if FAILS else 0


if __name__ == "__main__":
    sys.exit(main())

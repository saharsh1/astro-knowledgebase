#!/usr/bin/env python
"""Publish drafts: check each note in outbox/ and move the ones that pass into live/.

outbox/ mirrors live/: outbox/<arm>/lessons/X.md goes to live/<arm>/lessons/X.md,
outbox/papers/X.md to live/papers/X.md, outbox/requests/X.md to live/requests/X.md.

Usage:
    python scripts/publish_notes.py                    # list the drafts: ready or blocked, and why
    python scripts/publish_notes.py --apply            # move every ready draft into live/
    python scripts/publish_notes.py --apply --only outbox/requests/X.md [...]

A draft is blocked when:
- check_vault.py --draft finds an error at its destination (place, type, tags, name, links);
- a note with that name exists already (never overwrite: one writer per file);
- its author is not you (you publish only your own notes);
- it contains a review marker (rule 1) and has no `markers_reviewed: true`;
- it is a topic or digest without the AI-generated callout (rule 6).
Exit status 1 if any listed draft is blocked.
"""
from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from pathlib import Path

from kb_common import LIVE, OUTBOX, ROOT, frontmatter, github_user

AI_CALLOUT = "> [!note] Generated by"


def drafts(only: list[str]) -> list[Path]:
    if only:
        return [(ROOT / o).resolve() for o in only]
    return sorted(p for p in OUTBOX.rglob("*.md") if not p.name.startswith(".")) if OUTBOX.exists() else []


def check(draft: Path, user: str) -> tuple[Path, list[str], list[str]]:
    """(destination, reasons it is blocked, warnings)."""
    blocked, warns = [], []
    try:
        rel = draft.relative_to(OUTBOX.resolve())
    except ValueError:
        return draft, [f"not in {OUTBOX.name}/"], []
    dest = LIVE / rel
    if not draft.exists():
        return dest, ["file not found"], []
    fm = frontmatter(draft)
    if fm.get("author") != user:
        blocked.append(f"author is '{fm.get('author')}', not you ('{user}')")
    text = draft.read_text(encoding="utf-8")
    if (fm.get("type") == "topic" or draft.stem.startswith("Digest - ")) and AI_CALLOUT not in text:
        blocked.append("no AI-generated callout (rule 6)")
    r = subprocess.run([sys.executable, str(ROOT / "scripts" / "check_vault.py"), "--draft",
                        str(draft.relative_to(ROOT)), "--dest", str(dest.relative_to(ROOT))],
                       capture_output=True, text=True, cwd=ROOT)
    for line in r.stdout.splitlines():
        if line.startswith("error: "):
            blocked.append(line.removeprefix("error: ").split(": ", 1)[-1])
        elif line.startswith("warning: "):
            msg = line.removeprefix("warning: ")
            if "contains '" in msg and not fm.get("markers_reviewed"):
                blocked.append(msg.split(": ", 1)[-1] + " — read it, then add `markers_reviewed: true`")
            elif not msg.startswith("arms not synced"):
                warns.append(msg.split(": ", 1)[-1])
    return dest, blocked, warns


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true", help="move the ready drafts into live/")
    ap.add_argument("--only", nargs="+", default=[], help="only these drafts")
    a = ap.parse_args()
    if not LIVE.is_dir():
        sys.exit("live/ is missing: sync the Keeper library 'astro-kb-notes' into ./live first.")
    user = github_user()
    items = drafts(a.only)
    if not items:
        print("outbox/ is empty: nothing to publish.")
        return 0
    any_blocked = False
    for d in items:
        dest, blocked, warns = check(d, user)
        name = d.relative_to(ROOT) if d.is_relative_to(ROOT) else d
        if blocked:
            any_blocked = True
            print(f"BLOCKED  {name}")
            for b in blocked:
                print(f"         - {b}")
            continue
        if a.apply:
            if dest.exists():                                    # created since the check
                print(f"BLOCKED  {name}\n         - {dest.relative_to(ROOT)} exists already")
                any_blocked = True
                continue
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.move(str(d), str(dest))
            print(f"PUBLISHED {name} -> {dest.relative_to(ROOT)}")
        else:
            print(f"READY    {name} -> {dest.relative_to(ROOT)}")
        for w in warns:
            print(f"         (warning) {w}")
    if not a.apply:
        print("\nNothing moved. Run with --apply to publish the READY drafts.")
    return 1 if any_blocked else 0


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python
"""Write the entry pages of the vault from the notes' frontmatter (index keeper):

    keeper/generated/Home.md                     the entry point: arms, pinned, newest, status
    keeper/generated/Index - papers.md           the literature: every paper note, by source list
    keeper/generated/Index - lessons.md          every lesson of every arm, by status
    keeper/generated/<arm>/Arm - <Title>.md      one page per arm: its notes, lessons, topics, papers

Home.md keeps the text above the marker <!-- home:start -->; the block between the two
markers is replaced. The other pages are replaced whole. A note with `pinned: true` in its
frontmatter (set by the owner) is listed under "Pinned" on Home.

These pages are lists of links: the search index skips them (kb_pkg/index.py, SKIP_STEMS).

    python scripts/build/home.py               (also run by scripts/regenerate.sh and /publish-index)
    python scripts/build/home.py --bookmarks   any member: bookmark these pages in Obsidian (setup.sh)
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from kb_common import CONV, KEEPER, LIVE, ROOT, frontmatter, requests_, today  # noqa: E402

START, END = "<!-- home:start -->", "<!-- home:end -->"
ME = "scripts/build/home.py"
GENERATED = KEEPER / CONV["generated_folders"][0]
WIKILINK = re.compile(r"(?<!\!)\[\[([^\]|#]+)")
OWN_PAGE = re.compile(r"^(Home|Index - .+|Arm - .+)$")


# ---- reading the notes -------------------------------------------------------------------

def notes_in(folder: Path) -> list[Path]:
    return sorted(p for p in folder.rglob("*.md") if not p.name.startswith(".")) if folder.is_dir() else []


def created(fm: dict) -> str:
    return str(fm.get("created", ""))


def newest_first(paths: list[Path], fms: dict) -> list[Path]:
    return sorted(paths, key=lambda p: (created(fms[p]), p.stem), reverse=True)


def link(p: Path, label: str | None = None) -> str:
    return f"[[{p.stem}|{label}]]" if label and label != p.stem else f"[[{p.stem}]]"


def first_sentence(p: Path, fm: dict) -> str:
    """`summary:` of the frontmatter, else a lesson's **What.** line, else the first prose line."""
    if fm.get("summary"):
        return str(fm["summary"]).strip()
    text = p.read_text(encoding="utf-8")
    body = text[text.find("\n---", 4) + 4:] if text.startswith("---\n") else text
    what = re.search(r"\*\*What\.\*\*\s*(.+)", body)
    lines = [what.group(1)] if what else [l.strip() for l in body.splitlines()]
    for line in lines:
        if line and not line.startswith(("#", ">", "|", "-", "!", "[", "<", "`")):
            sentence = re.split(r"(?<=[a-z0-9)`])\. ", line)[0].rstrip(".") + "."
            return sentence if len(sentence) <= 220 else sentence[:217] + "…"
    return ""


def paper_label(p: Path) -> tuple[str, str]:
    """('Author et al (2023)', 'Title') from the file name 'Author et al (2023) - Title'."""
    short, _, title = p.stem.partition(" - ")
    return short, title


def header(title: str, tags: list[str], what: str) -> list[str]:
    return ["---", f'title: "{title}"', "type: hub", f'created: "{today()}"', f'author: "generated by {ME}"',
            f"tags: [{', '.join(tags)}]", "generated: true", "---",
            f"> [!info] Generated on {today()} by `{ME}` from {what}. Not written by an AI. "
            "Do not edit: rerun the script.", ""]


class Vault:
    """Every note of live/ and keeper/generated/ with its frontmatter, sorted into the lists
    the pages need."""

    def __init__(self) -> None:
        self.arms: dict[str, dict] = CONV["arms"]
        self.fms: dict[Path, dict] = {}
        self.by_arm: dict[str, dict[str, list[Path]]] = {}
        for arm in self.arms:
            self.by_arm[arm] = {f: notes_in(LIVE / arm / f) for f in CONV["arm_folders"]}
            generated = [p for p in notes_in(GENERATED / arm) if not OWN_PAGE.match(p.stem)]
            self.by_arm[arm]["generated"] = generated
        self.papers = [p for p in notes_in(LIVE / "papers") if frontmatter(p).get("type") == "paper"]
        for p in self.papers + [q for lists in self.by_arm.values() for l in lists.values() for q in l]:
            self.fms[p] = frontmatter(p)
        self.paper_arms = self._paper_arms()

    def _paper_arms(self) -> dict[Path, list[str]]:
        """A paper belongs to the arms in its `arms:` and to every arm with a note that links to it
        (the same rule as the search index)."""
        by_stem = {p.stem: p for p in self.papers}
        arms = {p: set(self.fms[p].get("arms") or []) & set(self.arms) for p in self.papers}
        for arm, lists in self.by_arm.items():
            for folder in CONV["arm_folders"]:
                for note in lists[folder]:
                    for target in WIKILINK.findall(note.read_text(encoding="utf-8", errors="replace")):
                        paper = by_stem.get(target.strip().rstrip("\\"))
                        if paper:
                            arms[paper].add(arm)
        return {p: sorted(a, key=list(self.arms).index) for p, a in arms.items()}

    def of_arm(self, arm: str, folder: str) -> list[Path]:
        return self.by_arm[arm][folder]

    def digests(self, arm: str) -> list[Path]:
        return [p for p in self.of_arm(arm, "notes") if p.stem.startswith("Digest - ")]

    def plain_notes(self, arm: str) -> list[Path]:
        return [p for p in self.of_arm(arm, "notes") if not p.stem.startswith("Digest - ")]

    def hubs(self, arm: str) -> list[Path]:
        """The generated entry notes of an arm: data-model hubs, documentation roots, code summaries."""
        notes = self.of_arm(arm, "generated")
        keep = [p for p in notes if self.fms[p].get("type") in ("hub", "code-summary")]
        # the front page of a release's documentation: its section note with the shortest address
        sections: dict[str, list[Path]] = {}
        for p in notes:
            if self.fms[p].get("type") == "gaia-section" and self.fms[p].get("url"):
                sections.setdefault(str(self.fms[p].get("release")), []).append(p)
        for release_notes in sections.values():
            keep.append(min(release_notes, key=lambda p: len(str(self.fms[p]["url"]))))
        return sorted(keep, key=lambda p: p.stem)

    def papers_of(self, arm: str) -> list[Path]:
        return [p for p in self.papers if arm in self.paper_arms[p]]

    def all_of(self, folder: str) -> list[Path]:
        return [p for arm in self.arms for p in self.of_arm(arm, folder)]

    def arm_of(self, p: Path) -> str:
        return p.relative_to(LIVE).parts[0]


# ---- the pages ---------------------------------------------------------------------------

def arm_page_name(arm: str) -> str:
    return f"Arm - {CONV['arms'][arm]['title']}"


def lesson_line(v: Vault, p: Path) -> str:
    fm = v.fms[p]
    confirmed = len(fm.get("confirmed_by") or [])
    facts = [str(fm.get("kind", "")), str(fm.get("status", "")), created(fm), str(fm.get("author", ""))]
    if confirmed:
        facts.append(f"confirmed by {confirmed}")
    return f"- {link(p, fm.get('title'))} — {', '.join(f for f in facts if f)}"


def paper_line(v: Vault, p: Path, with_arms: bool = True) -> str:
    short, title = paper_label(p)
    arms = ", ".join(v.arms[a]["title"] for a in v.paper_arms[p])
    pdf = "" if v.fms[p].get("pdf") else " (no PDF)"
    return f"- {link(p, short)} — {title}{pdf}" + (f" · *{arms}*" if with_arms and arms else "")


def by_year(v: Vault, papers: list[Path]) -> list[Path]:
    return sorted(papers, key=lambda p: (-int(v.fms[p].get("paper_year") or 0), p.stem))


def papers_page(v: Vault) -> str:
    groups: dict[str, list[Path]] = {}
    for p in v.papers:
        source = str(v.fms[p].get("source_list") or "")
        group = source.split("): ", 1)[1] if "): " in source else (source or "Added by members")
        groups.setdefault(group, []).append(p)
    out = header("Index - papers", ["Gaia"], "the paper notes in `live/papers/`")
    out += ["# Papers", "",
            f"Back to [[Home]]. {len(v.papers)} papers. Ask for one with `/request-paper <arXiv id or DOI>`; "
            "a curator adds it with `/ingest`.", "",
            "After each paper: the arms it belongs to (its own, and every arm with a note that cites it).", ""]
    counts = ", ".join(f"[[{arm_page_name(a)}|{v.arms[a]['title']}]] {len(v.papers_of(a))}" for a in v.arms
                       if v.papers_of(a))
    out += [f"By arm: {counts}." if counts else "No paper belongs to an arm yet.", ""]
    for group in sorted(groups):
        out += [f"## {group} ({len(groups[group])})", ""]
        out += [paper_line(v, p) for p in by_year(v, groups[group])]
        out.append("")
    return "\n".join(out)


def lessons_page(v: Vault) -> str:
    lessons = newest_first(v.all_of("lessons"), v.fms)
    out = header("Index - lessons", ["Gaia"], "the lessons' frontmatter")
    out += ["# Lessons", "", f"Back to [[Home]]. Lessons: {len(lessons)}. Record one with `/lesson`, then `/publish`.", ""]
    for status in [*CONV["enums"]["status"], "no status"]:
        rows = [p for p in lessons if str(v.fms[p].get("status") or "no status") == status]
        if not rows:
            continue
        out += [f"## {status.capitalize()} ({len(rows)})", ""]
        for p in rows:
            arm = v.arms[v.arm_of(p)]["title"]
            applies = ", ".join(f"`{a}`" for a in (v.fms[p].get("applies_to") or [])[:3])
            pin = " 📌" if v.fms[p].get("pinned") else ""
            out.append(lesson_line(v, p) + pin + f" · *{arm}*" + (f" · applies to {applies}" if applies else ""))
            what = first_sentence(p, v.fms[p])
            if what:
                out.append(f"  - {what}")
        out.append("")
    return "\n".join(out)


def arm_page(v: Vault, arm: str) -> str:
    spec = v.arms[arm]
    lower = [a for a in v.arms if v.arms[a]["layer"] < spec["layer"]]
    out = header(arm_page_name(arm), ["Gaia"], f"the notes of the arm `{arm}`")
    out += [f"# {spec['title']}", "", f"Back to [[Home]]. Arm `{arm}`, layer {spec['layer']}.", ""]
    if lower:
        names = ", ".join(f"[[{arm_page_name(a)}|{v.arms[a]['title']}]]" for a in lower)
        out += [f"Notes here may link down to: {names}.", ""]
    else:
        out += ["The lowest layer: notes here link only to notes of this arm.", ""]
    out += [f"Tags of this arm: {', '.join('`' + t + '`' for t in spec.get('tags', []))}.", ""]

    def section(title: str, rows: list[str], empty: str) -> list[str]:
        return [f"## {title} ({len(rows)})", "", *(rows or [empty]), ""]

    hubs = v.hubs(arm)
    if hubs:
        out += section("Generated from the sources", [f"- {link(p, v.fms[p].get('title'))}" for p in hubs], "")
    out += section("Topics", [f"- {link(p, v.fms[p].get('title'))} — {created(v.fms[p])}"
                              for p in newest_first(v.of_arm(arm, "topics"), v.fms)],
                   "None yet. `/consolidate <topic>` merges the notes on one topic.")
    out += section("Lessons", [lesson_line(v, p) for p in newest_first(v.of_arm(arm, "lessons"), v.fms)],
                   "None yet. Record one with `/lesson`.")
    out += section("Digests", [f"- {link(p, v.fms[p].get('title'))} — {created(v.fms[p])}, {v.fms[p].get('author', '')}"
                               for p in newest_first(v.digests(arm), v.fms)],
                   "None yet. Write one with `/digest <topic>`.")
    out += section("Notes", [f"- {link(p, v.fms[p].get('title'))} — {created(v.fms[p])}, {v.fms[p].get('author', '')}"
                             for p in newest_first(v.plain_notes(arm), v.fms)], "None yet.")
    discussion = v.of_arm(arm, "discussion")
    if discussion:
        out += section("Discussion", [f"- {link(p)} — about {v.fms[p].get('about', '')}"
                                      for p in newest_first(discussion, v.fms)], "")
    out += section("Papers", [paper_line(v, p, with_arms=False) for p in by_year(v, v.papers_of(arm))],
                   "None yet. Ask for one with `/request-paper`.")
    out += ["All papers: [[Index - papers]].", ""]
    return "\n".join(out)


def status_lines() -> list[str]:
    meta_file = KEEPER / "index" / "current" / "index_meta.json"
    meta = json.loads(meta_file.read_text()) if meta_file.exists() else {}
    sources = yaml.safe_load((ROOT / "sources.yaml").read_text()) if (ROOT / "sources.yaml").exists() else {}
    releases = sources.get("gaia") or []
    lines = []
    if meta:
        lines.append(f"- Search index: **{meta.get('version')}**, published by {meta.get('built_by', '—')} on "
                     f"{str(meta.get('date', ''))[:10]}: {meta.get('passages', '—')} passages from "
                     f"{meta.get('sources', '—')} sources.")
        if meta.get("notes_snapshot"):
            lines.append(f"- Notes snapshot behind that index: `{meta['notes_snapshot']}` (`keeper/snapshots/`).")
    else:
        lines.append("- Search index: none published yet.")
    for r in releases if isinstance(releases, list) else []:
        if isinstance(r, dict) and r.get("label"):
            lines.append(f"- Gaia {r['label']}: {r.get('status', '')}, documentation {r.get('doc_version', '—')}"
                         + (f". To be replaced by {r['replaced_by']}" if r.get("replaced_by") else "") + ".")
    lines.append(f"- Rules version {CONV['version']} (`conventions.yaml`); owner: {CONV['owner']}.")
    return lines


def home_block(v: Vault) -> str:
    lessons = newest_first(v.all_of("lessons"), v.fms)
    digests = newest_first([p for a in v.arms for p in v.digests(a)], v.fms)
    topics = newest_first(v.all_of("topics"), v.fms)
    pinned = [p for p in v.fms if v.fms[p].get("pinned")]
    open_requests = [r for r in requests_() if r["state"] == "open" and r["where"] == "live"]

    out = [START,
           f"> [!info] Generated on {today()} by `{ME}` (run by `/publish-index`). Not written by an AI. "
           "Write your own text above the start marker; the block below is replaced.", "",
           "## Start here", "",
           "| If you want to… | Do this |", "|---|---|",
           "| install on a new machine | read `docs/install.md` |",
           "| start a session up to date | `/sync` in Claude Code |",
           "| ask a question | ask Claude: it searches the papers, the Gaia documentation, the code and the notes |",
           "| record something the group should know | `/lesson`, then `/publish` |",
           "| a summary of what we have on a topic | `/digest <topic>`, then `/publish` |",
           "| a paper added | `/request-paper <arXiv id or DOI>` |", ""]
    if pinned:
        out += ["## 📌 Pinned", ""]
        out += [f"- {link(p, v.fms[p].get('title'))} — {first_sentence(p, v.fms[p])}" for p in pinned]
        out.append("")

    out += ["## Arms", "",
            "Layers: a note links only to its own arm or to a lower layer (science → software → Gaia).", "",
            "| Arm | Layer | Topics | Lessons | Digests | Notes | Papers |", "|---|---|---|---|---|---|---|"]
    for arm in sorted(v.arms, key=lambda a: v.arms[a]["layer"]):
        out.append(f"| [[{arm_page_name(arm)}\\|{v.arms[arm]['title']}]] | {v.arms[arm]['layer']} | "
                   f"{len(v.of_arm(arm, 'topics'))} | {len(v.of_arm(arm, 'lessons'))} | {len(v.digests(arm))} | "
                   f"{len(v.plain_notes(arm))} | {len(v.papers_of(arm))} |")
    out.append("")

    out += [f"## Lessons ({len(lessons)})", ""]
    out += [lesson_line(v, p) for p in lessons[:5]] or ["None yet. Record one with `/lesson`."]
    out += ["", "All lessons: [[Index - lessons]].", ""]
    if topics:
        out += [f"## Topics ({len(topics)})", ""]
        out += [f"- {link(p, v.fms[p].get('title'))} — {created(v.fms[p])}" for p in topics[:5]]
        out.append("")
    out += [f"## Digests ({len(digests)})", ""]
    out += [f"- {link(p, v.fms[p].get('title'))} — {created(v.fms[p])}, {v.arms[v.arm_of(p)]['title']}"
            for p in digests[:5]] or ["None yet. Write one with `/digest <topic>`."]
    out.append("")

    with_pdf = sum(1 for p in v.papers if v.fms[p].get("pdf"))
    out += [f"## Literature ({len(v.papers)} papers)", "",
            f"All papers by source list: [[Index - papers]]. {with_pdf} of {len(v.papers)} have their PDF in Keeper.", ""]
    if open_requests:
        out += [f"Open paper requests: {len(open_requests)} (`live/requests/`); a curator runs `/ingest`.", ""]

    out += ["## Gaia documentation", ""]
    out += [f"- {link(p, v.fms[p].get('title'))}" for p in v.hubs("gaia")] if "gaia" in v.arms else []
    out += ["- Exact column facts in a session: `lookup_column(table, column)`, `find_columns(text)`.", "",
            "## Software", ""]
    for p in v.hubs("software") if "software" in v.arms else []:
        fm = v.fms[p]
        out.append(f"- {link(p, str(fm.get('repo') or fm.get('title')))} — pinned at `{str(fm.get('commit', ''))[:12]}`"
                   f" of {fm.get('commit_date', '')}")
    out += ["", "## Status", "", *status_lines(), "", END]
    return "\n".join(out)


def write_home(block: str) -> None:
    home = GENERATED / "Home.md"
    head = ("---\ntitle: Home\ntype: hub\n" f'created: "{today()}"\nauthor: {CONV["owner"]}\ntags: [Gaia]\n---\n'
            "# Astro knowledge base\n\nThe group's shared knowledge: the Gaia documentation and papers, the "
            "group's code, and the notes of each science arm — searchable with Claude.\n\n")
    if home.exists():
        text = home.read_text(encoding="utf-8")
        head = text.split(START)[0] if START in text else text.rstrip() + "\n\n"
    home.write_text(head + block + "\n", encoding="utf-8")


def bookmarks() -> int:
    """Write .obsidian/bookmarks.json (local, not in git) with the entry pages, unless the
    user already has bookmarks."""
    target = ROOT / ".obsidian" / "bookmarks.json"
    if target.exists():
        print(".obsidian/bookmarks.json exists: left as it is.")
        return 0
    pages = [GENERATED / "Home.md", GENERATED / "Index - papers.md", GENERATED / "Index - lessons.md"]
    pages += [GENERATED / arm / f"{arm_page_name(arm)}.md" for arm in CONV["arms"]]
    items = [{"type": "file", "path": p.relative_to(ROOT).as_posix(),
              "title": p.stem.removeprefix("Index - ").removeprefix("Arm - ").capitalize() if p.stem.startswith("Index")
              else p.stem.removeprefix("Arm - ")} for p in pages if p.exists()]
    target.parent.mkdir(exist_ok=True)
    target.write_text(json.dumps({"items": items}, indent=2) + "\n", encoding="utf-8")
    print(f".obsidian/bookmarks.json written: {len(items)} bookmarks (Home, papers, lessons, the arms).")
    return 0


def main() -> int:
    if "--bookmarks" in sys.argv[1:]:
        return bookmarks()
    if not GENERATED.is_dir() or not LIVE.is_dir():
        sys.exit("keeper/generated/ or live/ is missing: sync the two Keeper libraries first.")
    v = Vault()
    pages = {GENERATED / "Index - papers.md": papers_page(v), GENERATED / "Index - lessons.md": lessons_page(v)}
    for arm in v.arms:
        pages[GENERATED / arm / f"{arm_page_name(arm)}.md"] = arm_page(v, arm)
    for path, text in pages.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text.rstrip() + "\n", encoding="utf-8")
    write_home(home_block(v))
    print(f"Home and {len(pages)} pages written to keeper/generated/: {len(v.arms)} arms, "
          f"lessons {len(v.all_of('lessons'))}, papers {len(v.papers)}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
